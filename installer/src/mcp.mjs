// MCP servers: stdio servers are installed ahead of time with pnpm at an exact
// version (never fetched by npx at runtime); both kinds are rendered into the
// root-owned config each Agent reads. Secrets are passed by environment variable
// name only: the rendered files reference names, never values. The list of
// Named Secrets is written by the install modes (secrets.mjs), MCP or not.
import { mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { parse as parseToml, stringify as stringifyToml } from 'smol-toml';
import { ManifestError, describeEntry } from './validate.mjs';
import { secretNames } from './secrets.mjs';
import { writeAtomic } from './files.mjs';

// The pnpm supply-chain policy (ADR 0001). The image sets it as env for dev-user
// shells, but a build step and the root start-up step do not see that metadata,
// so the installer states it itself rather than inherit whatever the env holds.
const PNPM_POLICY = {
  pnpm_config_minimum_release_age: '10080',
  pnpm_config_minimum_release_age_strict: 'true',
  pnpm_config_trust_policy: 'no-downgrade',
  pnpm_config_strict_dep_builds: 'true',
  pnpm_config_block_exotic_subdeps: 'true',
};
const BLOCK_BEGIN = '# BEGIN dev-setup mcp_servers (generated by the extension installer; do not edit)';
const BLOCK_END = '# END dev-setup mcp_servers';

const isMcp = (e) => e.kind === 'mcp' || e.kind === 'mcp-remote';

/** Resolve the executable file of an installed package from its `bin` field. */
function binPath(pkgDir, pkgName) {
  const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
  let bin = pkg.bin;
  if (typeof bin === 'object' && bin !== null) {
    const names = Object.keys(bin);
    const short = pkgName.split('/').pop();
    const pick = names.length === 1 ? names[0] : names.find((n) => n === short);
    if (!pick) throw new Error(`package has several bins (${names.join(', ')}) and none is named "${short}"`);
    bin = bin[pick];
  }
  if (typeof bin !== 'string') throw new Error('package declares no "bin"; a stdio MCP server must be an executable package');
  return join(pkgDir, bin);
}

/** Where a stdio entry lives once installed: /opt/dev-setup/mcp/<name>. */
export const mcpDir = (mcpRoot, entry) => join(mcpRoot, entry.name);

/**
 * Install each stdio entry with pnpm into its own directory. The pnpm policy
 * applies (7-day cooldown, no dependency build scripts, no downgrade of trust).
 */
export function installMcpPackages(extensions, { mcpRoot, overwrite = false }) {
  const installed = [];
  extensions.forEach((entry, i) => {
    if (entry.kind !== 'mcp') return;
    const dir = mcpDir(mcpRoot, entry);
    try {
      if (existsSync(dir)) {
        if (!overwrite) throw new Error(`${dir} already exists`);
        rmSync(dir, { recursive: true, force: true });
      }
      mkdirSync(dir, { recursive: true });
      writeFileSync(join(dir, 'package.json'), JSON.stringify({ name: `dev-setup-mcp-${entry.name}`, version: '0.0.0', private: true }));
      execFileSync('pnpm', ['add', '--save-exact', '--ignore-workspace', `${entry.source.npm}@${entry.source.version}`], {
        cwd: dir,
        env: { ...process.env, ...PNPM_POLICY },
        stdio: ['ignore', 'pipe', 'pipe'],
        encoding: 'utf8',
      });
      binPath(join(dir, 'node_modules', entry.source.npm), entry.source.npm); // fail now, not when an Agent starts
      execFileSync('chmod', ['-R', 'u+rwX,go-w,a+rX', dir]);
    } catch (err) {
      const detail = err.stderr || err.stdout || err.message;
      throw new ManifestError([`${entry.layer}: ${describeEntry(entry, i)}: cannot install ${entry.source.npm}@${entry.source.version}: ${String(detail).trim().split('\n').slice(-4).join(' ')}`]);
    }
    installed.push({ name: entry.name, package: entry.source.npm, version: entry.source.version });
  });
  return installed;
}

/** Launch command of an installed stdio entry: node on the pre-installed file. */
function stdioCommand(entry, mcpRoot) {
  return { command: 'node', args: [binPath(join(mcpDir(mcpRoot, entry), 'node_modules', entry.source.npm), entry.source.npm)] };
}

const forAgent = (extensions, agent) => extensions.filter((e) => isMcp(e) && e.agents.includes(agent));

/** Claude `managed-mcp.json`. `${NAME}` is expanded by Claude from its own environment. */
export function renderClaudeMcp(extensions, mcpRoot) {
  const mcpServers = {};
  for (const e of forAgent(extensions, 'claude')) {
    if (e.kind === 'mcp') {
      const s = { type: 'stdio', ...stdioCommand(e, mcpRoot) };
      if (secretNames(e).length) s.env = Object.fromEntries(secretNames(e).map((n) => [n, `\${${n}}`]));
      mcpServers[e.name] = s;
    } else {
      mcpServers[e.name] = { type: 'http', url: e.url };
      if (e.bearerTokenEnv) mcpServers[e.name].headers = { Authorization: `Bearer \${${e.bearerTokenEnv}}` };
    }
  }
  return { mcpServers };
}

/** Codex `mcp_servers` table. `env_vars` forwards the named variables from Codex's environment. */
export function renderCodexMcp(extensions, mcpRoot) {
  const servers = {};
  for (const e of forAgent(extensions, 'codex')) {
    if (e.kind === 'mcp') {
      const s = stdioCommand(e, mcpRoot);
      if (secretNames(e).length) s.env_vars = secretNames(e);
      servers[e.name] = s;
    } else {
      servers[e.name] = { url: e.url };
      if (e.bearerTokenEnv) servers[e.name].bearer_token_env_var = e.bearerTokenEnv;
    }
  }
  return servers;
}

/** Replace the generated block of a Codex config text, leaving the hand-written part untouched. */
export function withCodexMcpBlock(text, servers) {
  const stripped = text.replace(new RegExp(`\\n?${BLOCK_BEGIN.replace(/[()]/g, '\\$&')}[\\s\\S]*?${BLOCK_END}\\n?`), '\n').replace(/\n+$/, '\n');
  if (Object.keys(servers).length === 0) return stripped;
  const toml = stringifyToml({ mcp_servers: servers });
  const out = `${stripped}\n${BLOCK_BEGIN}\n${toml}\n${BLOCK_END}\n`;
  parseToml(out); // never leave an unparseable system config behind
  return out;
}

/**
 * Render MCP config for every layer's entries. Nothing is written when no
 * entry names an MCP server: Claude's `managed-mcp.json` takes exclusive control
 * of MCP servers, so the file exists only when something was declared.
 * @param {object[]} extensions merged entries of all layers
 */
export function writeMcpConfig(extensions, { mcpRoot, claudeMcp, codexConfig }) {
  const mcp = extensions.filter(isMcp);
  if (mcp.length === 0) return { servers: [] }; // touch nothing: no MCP, no config, no exclusive control
  const claude = renderClaudeMcp(extensions, mcpRoot);
  const codex = renderCodexMcp(extensions, mcpRoot);
  if (Object.keys(claude.mcpServers).length) writeAtomic(claudeMcp, `${JSON.stringify(claude, null, 2)}\n`);
  if (Object.keys(codex).length || (existsSync(codexConfig) && readFileSync(codexConfig, 'utf8').includes(BLOCK_BEGIN))) {
    writeAtomic(codexConfig, withCodexMcpBlock(existsSync(codexConfig) ? readFileSync(codexConfig, 'utf8') : '', codex));
  }
  return { servers: mcp.map((e) => e.name) };
}
